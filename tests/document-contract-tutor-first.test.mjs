import assert from 'node:assert/strict'
import fs from 'node:fs'
import {createRequire} from 'node:module'
const require=createRequire(import.meta.url),ts=require('typescript')
require.extensions['.ts']=(mod,file)=>mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{
 compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}
}).outputText,file)
const {orchestrateTutorFirst}=require('../server/core/tutor-first-orchestrator.ts')
const {reconcileDocumentContract}=require('../server/core/document-contract.ts')
const {documentContractStatePatch,mergeStatePatch,toWireState}=require('../server/core/state-manager.ts')
const {DEFAULT_SESSION_STATE}=require('../lib/contracts.ts')
const base=(extra={})=>({...DEFAULT_SESSION_STATE,activeMode:'interact',tokens:3,interfaceLanguage:'es',mentorProfile:'Sarah',...extra})
const plan=(msg,state)=>orchestrateTutorFirst({message:msg,state,interfaceLanguage:'es'})
const apply=(p,state,artifacts=[])=>mergeStatePatch(state,documentContractStatePatch(p,artifacts))
const pending=(level=null,topic=null)=>({type:'course_pdf',level,topic,status:'collecting',openedAtToken:2})
const open=plan('Quiero un curso completo en PDF',base())
assert.equal(open.executor,'mentor','tutor retains authoring')
assert.equal(open.documentContractUpdate?.level,null)
assert.equal(open.documentContractUpdate?.topic,null)
assert.equal(open.documentContractReady,false)
assert.equal(open.documentContractControlOnly,true,'no automatic milestone/schema during parameter collection')
assert.equal(apply(open,base()).pendingDocumentRequest?.status,'collecting')
const initial=base({pendingDocumentRequest:pending()})
const combined=plan('A1, sobre ser y estar',initial)
assert.equal(combined.documentContractUpdate?.level,'A1')
assert.equal(combined.documentContractUpdate?.topic,'ser y estar')
assert.equal(combined.documentContractReady,true)
assert.equal(combined.documentContractControlOnly,false,'ready contract permits tutor-authored PDF')
assert.equal(combined.executor,'mentor','no old second-model pdf generation')
const partial=plan('Nivel A1',initial)
assert.equal(partial.documentContractUpdate?.level,'A1')
assert.equal(partial.documentContractUpdate?.topic,null)
const topic=plan('Tema: gramática del español',base({pendingDocumentRequest:pending('A1')}))
assert.equal(topic.documentContractUpdate?.topic,'gramática del español')
const bare=plan('Ser y estar',base({pendingDocumentRequest:pending('A1')}))
assert.equal(bare.documentContractUpdate?.topic,'Ser y estar')
const full=plan('Quiero un curso sobre ser y estar de nivel A1 en PDF',base())
assert.equal(full.documentContractReady,true)
assert.equal(full.documentContractUpdate?.level,'A1')
assert.ok(full.documentContractUpdate?.topic?.includes('ser y estar'))
// No false success: the pending course survives an LLM/PDF failure.
assert.equal(apply(combined,initial,[]).pendingDocumentRequest?.status,'collecting')
assert.equal(documentContractStatePatch(combined,[{type:'quiz'}]).pendingDocumentRequest?.status,'collecting')
// An ACTUAL authored PDF settles the user-authorized contract.
assert.deepEqual(documentContractStatePatch(combined,[{type:'pdf'}]),{pendingDocumentRequest:null})
assert.deepEqual(documentContractStatePatch(combined,[{type:'course_pdf'}]),{pendingDocumentRequest:null})
const donePatch=documentContractStatePatch(combined,[{type:'pdf'}])
const after=mergeStatePatch(initial,donePatch)
assert.equal(after.pendingDocumentRequest,undefined)
assert.equal(toWireState(after,donePatch).pendingDocumentRequest,null,'wire null survives JSON transport')
const cancel=plan('Olvídalo.',initial)
assert.equal(cancel.executor,'mentor','cancellation does not give old gate cognitive control')
assert.equal(cancel.clearDocumentContract,true)
assert.equal(cancel.documentContractControlOnly,true,'cancellation must not generate a fifth-turn artifact')
assert.equal(apply(cancel,initial).pendingDocumentRequest,undefined)
const wirePatch=documentContractStatePatch(cancel)
assert.equal(JSON.parse(JSON.stringify(toWireState(apply(cancel,initial),wirePatch))).pendingDocumentRequest,null)
const redirect=plan('Cambiemos de tema. Cuéntame sobre la historia de Cartagena.',initial)
assert.equal(redirect.clearDocumentContract,true)
assert.equal(redirect.documentContractControlOnly,false,'redirect with new substantive task remains teachable')
assert.equal(redirect.executor,'mentor')
assert.equal(redirect.executionOrder[0].action,'conversation','redirect with immediate request cannot be swallowed')
assert.equal(apply(redirect,initial).pendingDocumentRequest,undefined)
const switched=plan('Corrige esto: Yo soy cansado',initial)
assert.equal(switched.clearDocumentContract,true)
assert.equal(switched.pedagogicalAction,'correction_only')
const quiz=plan('Hazme un quiz de español',initial)
assert.equal(quiz.clearDocumentContract,true)
assert.equal(quiz.executor,'mentor')
const format=plan('Quiero cambiar a formato HTML',initial)
assert.equal(format.clearDocumentContract,true)
const newRequest=plan('Quiero un curso de historia en PDF nivel B2',initial)
assert.equal(newRequest.documentContractReady,true,'explicit new course can replace old')
assert.equal(newRequest.documentContractUpdate?.level,'B2')
assert.equal(newRequest.documentContractUpdate?.topic,'historia')
const noContract=base()
assert.equal(plan('Hola',noContract).documentContractUpdate,undefined)
assert.equal(plan('Cambiemos de tema. Cuéntame algo.',noContract).clearDocumentContract,undefined)
const expires=plan('Siguiente',base({tokens:20,pendingDocumentRequest:pending('A1')}))
assert.equal(expires.clearDocumentContract,true)
// Same real code path and pure plan, no timing/randomness.
for(const msg of ['A1, sobre ser y estar','Olvídalo.','Cambiemos de tema. Cuéntame sobre Cartagena.']){
 const a=plan(msg,initial)
 for(let n=0;n<100;n++)assert.deepEqual(plan(msg,initial),a)
}
